function cardsForKind(kind) {
  const perMech = MECH[kind].map(({ m, titles, texts, params }) => {
    const list = [];
    for (const title of titles) for (const text of texts) list.push({ kind, mechanic: m, title, text, ...(params ? { params } : {}) });
    return shuffle(list);
  });
  // Round-robin по механикам, пока не наберём 100.
  const result = [];
  let i = 0;
  while (result.length < 100) {
    let added = false;
    for (const list of perMech) {
      if (list[i]) {
        result.push(list[i]);
        added = true;
        if (result.length >= 100) break;
      }
    }
    if (!added) break;
    i++;
  }
  return result;
}

let idc = 0;
const all = [];
for (const kind of ['active', 'on_eliminated', 'on_survived']) {
  for (const c of cardsForKind(kind)) {
    all.push({ id: `${kind}-${idc++}`, ...c });
  }
}

fs.writeFileSync(out, JSON.stringify(all, null, 0) + '\n', 'utf8');
const by = (k) => all.filter((c) => c.kind === k).length;
