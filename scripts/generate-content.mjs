function mulberry32(seed) {
  return function () {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rng = mulberry32(20261116);
function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
function combineN(pools, format, target) {
  const results = [];
  const rec = (i, acc) => {
    if (i === pools.length) return void results.push(format(acc));
    for (const v of pools[i]) rec(i + 1, [...acc, v]);
  };
  rec(0, []);
  const uniq = [...new Set(results.map((s) => s.replace(/\s+/g, ' ').trim()))];
  return shuffle(uniq).slice(0, target);
}

let idCounter = 0;
function trait(category, text, tags = []) {
  return { id: `${category}-${idCounter++}`, category, text: text.trim(), tags };
}
function build(category, tagged, filler, target) {
  const out = [];
  const seen = new Set();
  const push = (text, tags) => {
    const key = text.replace(/\s+/g, ' ').trim();
    if (!key || seen.has(key)) return;
    seen.add(key);
    out.push(trait(category, key, tags));
  };
  for (const [text, tags] of tagged) push(text, tags);
  for (const text of filler) {
    if (out.length >= target) break;
    push(text, []);
  }
  return out.slice(0, target);
}
function plural(n) {
  const d = n % 10,
    dd = n % 100;
  if (dd >= 11 && dd <= 14) return 'лет';
  if (d === 1) return 'год';
  if (d >= 2 && d <= 4) return 'года';
  return 'лет';
}

